(function () {
  "use strict";

  var LANG_KEY = "tabby-lang";
  var DEFAULT_LANG = "it";
  var SUPPORTED = ["it", "en", "fr", "de", "es"];

  var GUEST_LABELS = {
    it: function (n) { return n + (n === 1 ? " ospite" : " ospiti"); },
    en: function (n) { return n + (n === 1 ? " guest" : " guests"); },
    fr: function (n) { return n + (n === 1 ? " personne" : " personnes"); },
    de: function (n) { return n + (n === 1 ? " Gast" : " Gäste"); },
    es: function (n) { return n + (n === 1 ? " huésped" : " huéspedes"); },
  };

  function getLang() {
    try {
      var stored = localStorage.getItem(LANG_KEY);
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
    } catch (e) {
      /* ignore */
    }
    return DEFAULT_LANG;
  }

  function setLang(lang) {
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch (e) {
      /* ignore */
    }
  }

  function t(key, lang) {
    var dict = window.TABBY_TRANSLATIONS && window.TABBY_TRANSLATIONS[lang];
    return dict ? dict[key] : undefined;
  }

  function applyLanguage(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = DEFAULT_LANG;
    document.documentElement.lang = lang;

    if (lang !== DEFAULT_LANG) {
      document.querySelectorAll("[data-i18n]").forEach(function (el) {
        var val = t(el.getAttribute("data-i18n"), lang);
        if (val === undefined) return;
        if (el.hasAttribute("data-i18n-html")) {
          el.innerHTML = val;
        } else {
          el.textContent = val;
        }
      });
      document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
        var val = t(el.getAttribute("data-i18n-placeholder"), lang);
        if (val !== undefined) el.setAttribute("placeholder", val);
      });
      document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
        var val = t(el.getAttribute("data-i18n-aria"), lang);
        if (val !== undefined) el.setAttribute("aria-label", val);
      });
      document.querySelectorAll("[data-i18n-content]").forEach(function (el) {
        var val = t(el.getAttribute("data-i18n-content"), lang);
        if (val !== undefined) el.setAttribute("content", val);
      });
    } else {
      /* Switching back to Italian: reload so the original markup (source
         of truth for the default language) is restored exactly. */
    }

    document.querySelectorAll("[data-lang-switch]").forEach(function (el) {
      el.value = lang;
    });

    document.dispatchEvent(new CustomEvent("tabby:langchange", { detail: { lang: lang } }));
  }

  window.TabbyI18n = {
    getLang: getLang,
    guestsLabel: function (n) {
      var lang = getLang();
      var fn = GUEST_LABELS[lang] || GUEST_LABELS.it;
      return fn(n);
    },
  };

  document.addEventListener("DOMContentLoaded", function () {
    var current = getLang();

    document.querySelectorAll("[data-lang-switch]").forEach(function (select) {
      select.value = current;
      select.addEventListener("change", function () {
        var next = select.value;
        setLang(next);
        if (next === DEFAULT_LANG) {
          window.location.reload();
        } else {
          applyLanguage(next);
        }
      });
    });

    if (current !== DEFAULT_LANG) {
      applyLanguage(current);
    }
  });
})();
